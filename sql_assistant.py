from pathlib import Path

from langchain_community.utilities import SQLDatabase
from langchain_ollama import OllamaLLM
from langchain_experimental.sql import SQLDatabaseChain


# --------------------------------------------------
# 1. Database configuration
# --------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent
DB_PATH = BASE_DIR / "database" / "retail.db"

db = SQLDatabase.from_uri(
    f"sqlite:///{DB_PATH}"
)


# --------------------------------------------------
# 2. Load Ollama model
# --------------------------------------------------

llm = OllamaLLM(
    model="codellama",
    temperature=0
)


# --------------------------------------------------
# 3. Create SQL generation chain
# --------------------------------------------------

db_chain = SQLDatabaseChain.from_llm(
    llm=llm,
    db=db,
    verbose=True,
    return_sql=True
)


# --------------------------------------------------
# 4. Reusable SQL generation function
# --------------------------------------------------

def generate_sql(question):
    """
    Convert a natural-language question into clean SQL.

    Parameters
    ----------
    question : str
        User's natural-language database question.

    Returns
    -------
    str
        Clean SQL query generated by the LLM.
    """

    response = db_chain.invoke({
        "query": question
    })

    generated_text = response["result"]

    # Extract SQL from the chain response
    if "SQLQuery:" in generated_text:
        sql = generated_text.split("SQLQuery:", 1)[1].strip()
    else:
        sql = generated_text.strip()

    # Remove Markdown code fences
    sql = sql.replace("```sql", "")
    sql = sql.replace("```", "")
    sql = sql.strip()

    return sql


# --------------------------------------------------
# 5. Test the reusable function
# --------------------------------------------------

if __name__ == "__main__":

    question = "Which product generated the highest revenue?"

    sql = generate_sql(question)

    print("\nGenerated SQL:")
    print(sql)